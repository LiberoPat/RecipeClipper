import Foundation

// RecipeClipper's regex-vs-LLM evaluation (#105). A dev tool: compiled by run.sh against the
// iOS app's pure Data/Model sources, never shipped. Usage: run.sh [tasks…] [--no-llm]
//   tasks: ingredients pages decisions chef (default: all). Results land in results/.
let args = Array(CommandLine.arguments.dropFirst())
let llm = !args.contains("--no-llm")
let chosen = args.filter { !$0.hasPrefix("--") }
let tasks = chosen.isEmpty ? ["ingredients", "pages", "decisions", "chef"] : chosen

try? FileManager.default.createDirectory(atPath: "results", withIntermediateDirectories: true)
var report = "<!-- generated by tools/eval/run.sh; model \(Llm.model) -->\n\n"
for task in tasks {
    let started = Date()
    switch task {
    case "ingredients":
        report += IngredientsTask.run("gold/ingredients.jsonl", title: "Ingredient lines from the corpus (#33): first amount",
                                      log: "ingredients-corpus", llm: llm) + "\n"
        report += IngredientsTask.run("gold/ingredients-heldout.jsonl", title: "Held-out lines from the site-check pages: first amount",
                                      log: "ingredients-heldout", llm: llm)
    case "pages": report += PagesTask.run(".cache/pages", llm: llm)
    case "decisions": report += DecisionsTask.run("gold/decisions.jsonl", llm: llm)
    case "chef": report += ChefTask.run(".cache/pages", llm: llm)
    case "dump-lines": // the pages' JSON-LD ingredient lines, to label a held-out gold set
        for page in EvalPage.load(".cache/pages") { print(page.gold.ingredients.joined(separator: "\n")) }
    default: print("unknown task \(task)")
    }
    report += "\n"
    FileHandle.standardError.write("\(task): \(Int(Date().timeIntervalSince(started))) s\n".data(using: .utf8)!)
}
try? report.write(toFile: "results/\(tasks.joined(separator: "-")).md", atomically: true, encoding: .utf8)
print(report)
